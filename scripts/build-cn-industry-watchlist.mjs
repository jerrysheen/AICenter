function yahooSymbol(ticker) {
  const code = String(ticker).padStart(6, '0');
  return /^[569]/.test(code) ? `${code}.SS` : `${code}.SZ`;
}

const merged = new Map();
for (const [name, ticker, group, summary] of RAW) {
  const key = `${ticker}::${group}`;
  const previous = merged.get(key);
  if (!previous) {
    merged.set(key, { name, ticker, group, summary });
    continue;
  }
  if (!previous.summary.includes(summary)) previous.summary = `${previous.summary}；${summary}`;
}

